def resonance_arrays():
    """Columns: E0 [eV], Gamma [eV], sigma0*Gg/G [b], sigma0*Gn/G [b] (SLBW peak values)."""
    A = MASS[1]
    out = []
    for E0, gn, gg in RES_U238_PARAMS:
        gn, gg = gn * 1e-3, gg * 1e-3
        G = gn + gg
        s0 = 2.608e6 * ((A + 1) / A) ** 2 / E0 * gn / G      # g = 1 for U-238 s-waves
        out.append([E0, G, s0 * gg / G, s0 * gn / G])
    return np.array(out)


